# 하위호환: 기존 코드에서 참조하던 변수 유지
BRAILLE = {}


def decompose_hangul(char: str) -> tuple[str, str, str]:
    """한글 음절을 초성·중성·종성으로 분해"""
    code = ord(char) - 0xAC00
    cho  = code // 588
    jung = (code % 588) // 28
    jong = code % 28
    return CHO_LIST[cho], JUNG_LIST[jung], JONG_LIST[jong]


def convert_to_braille(text: str) -> str:
    """한글 텍스트를 점자 유니코드 문자열로 변환"""
    result = ""
    for char in text:
        if 0xAC00 <= ord(char) <= 0xD7A3:
            cho, jung, jong = decompose_hangul(char)
            result += _CHO.get(cho, "")
            result += _JUNG.get(jung, "")
            if jong:
                result += _JONG.get(jong, "")
        else:
            result += char
    return result
